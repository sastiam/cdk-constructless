import { Stack } from 'aws-cdk-lib';
import * as iam from 'aws-cdk-lib/aws-iam';
import type * as kms from 'aws-cdk-lib/aws-kms';
import * as sns from 'aws-cdk-lib/aws-sns';
import * as subs from 'aws-cdk-lib/aws-sns-subscriptions';
import { Construct } from 'constructs';
import { suppressNag } from '../core/nag';
import { assertEmails, assertItemCount } from '../core/validation';

/**
 * Properties of the `AlertsTopic` construct.
 */
export interface AlertsTopicProps {
  /**
   * The physical name of the SNS topic. Leave it unset to let CDK generate a unique name.
   *
   * @default a name generated by CDK
   */
  readonly topicName?: string;

  /**
   * The e-mail addresses that subscribe to the topic. Between 0 and 10 items; each must be a valid e-mail address.
   * Each address must confirm its subscription before it receives notifications.
   *
   * @default [] (no e-mail subscribers)
   */
  readonly emails?: string[];

  /**
   * Whether AWS Budgets may publish to the topic. Adds the `AWSBudgetsSNSPublishingPermissions` statement, which is restricted to
   * budgets in this account.
   *
   * @default true
   */
  readonly allowBudgets?: boolean;

  /**
   * Whether Cost Anomaly Detection may publish to the topic. Adds the `AWSAnomalyDetectionSNSPublishingPermissions` statement.
   *
   * @default false
   */
  readonly allowCostAnomalyDetection?: boolean;

  /**
   * The customer managed KMS key that encrypts the topic. When given, Budgets (and Cost Anomaly Detection when allowed) are granted
   * `kms:GenerateDataKey*` and `kms:Decrypt` on the key. The key is not created by this construct.
   *
   * @default none (the topic is not encrypted with a customer managed key)
   */
  readonly masterKey?: kms.IKey;
}

/**
 * A notification-only SNS topic for cost and budget alerts, with e-mail subscriptions and the topic policy that AWS Budgets
 * and Cost Anomaly Detection need to publish to it.
 *
 * The topic is for human notifications only. Never subscribe automation (Lambda, SSM) to it: a first-cent alert on a topic that
 * also triggers automation would stop every instance. Use a Budget Action to act on spend instead.
 *
 * Budgets topics must be in the same account as the budget; the Budgets statement is restricted with `aws:SourceAccount`
 * and `aws:SourceArn`.
 *
 * The topic enforces TLS (`enforceSSL`). Without `masterKey`, cdk-nag reports `AwsSolutions-SNS2`, which this construct acknowledges
 * with the reason "A KMS key costs 1 USD per month; this topic carries no sensitive data; pass masterKey to encrypt".
 */
export class AlertsTopic extends Construct {
  /**
   * The wrapped `AWS::SNS::Topic` resource.
   */
  public readonly topic: sns.Topic;

  /**
   * @param scope the parent construct
   * @param id the construct id
   * @param props the topic properties
   * @throws {ConstructValidationError} when `emails` does not contain 0 to 10 items, or when an `emails` entry is not a valid e-mail address
   */
  constructor(scope: Construct, id: string, props: AlertsTopicProps = {}) {
    super(scope, id);

    const stack = Stack.of(this);
    const emails = props.emails ?? [];
    const allowBudgets = props.allowBudgets ?? true;
    const allowCostAnomalyDetection = props.allowCostAnomalyDetection ?? false;
    const masterKey = props.masterKey;

    assertItemCount(this, 'emails', emails, 0, 10);
    assertEmails(this, 'emails', emails);

    this.topic = new sns.Topic(this, 'Topic', {
      enforceSSL: true,
      masterKey,
      topicName: props.topicName,
    });

    for (const email of emails) {
      this.topic.addSubscription(new subs.EmailSubscription(email));
    }

    if (allowBudgets) {
      this.topic.addToResourcePolicy(
        new iam.PolicyStatement({
          sid: 'AWSBudgetsSNSPublishingPermissions',
          principals: [new iam.ServicePrincipal('budgets.amazonaws.com')],
          actions: ['SNS:Publish'],
          resources: [this.topic.topicArn],
          conditions: {
            StringEquals: { 'aws:SourceAccount': stack.account },
            ArnLike: { 'aws:SourceArn': `arn:${stack.partition}:budgets::${stack.account}:*` },
          },
        }),
      );
      masterKey?.grant(new iam.ServicePrincipal('budgets.amazonaws.com'), 'kms:GenerateDataKey*', 'kms:Decrypt');
    }

    if (allowCostAnomalyDetection) {
      this.topic.addToResourcePolicy(
        new iam.PolicyStatement({
          sid: 'AWSAnomalyDetectionSNSPublishingPermissions',
          principals: [new iam.ServicePrincipal('costalerts.amazonaws.com')],
          actions: ['SNS:Publish'],
          resources: [this.topic.topicArn],
        }),
      );
      masterKey?.grant(new iam.ServicePrincipal('costalerts.amazonaws.com'), 'kms:GenerateDataKey*', 'kms:Decrypt');
    }

    if (!masterKey) {
      suppressNag(this.topic, [
        {
          id: 'AwsSolutions-SNS2',
          reason: 'A KMS key costs 1 USD per month; this topic carries no sensitive data; pass masterKey to encrypt',
        },
      ]);
    }
  }
}
