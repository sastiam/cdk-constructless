import { Duration, Token } from 'aws-cdk-lib';
import * as cloudwatch from 'aws-cdk-lib/aws-cloudwatch';
import * as cw_actions from 'aws-cdk-lib/aws-cloudwatch-actions';
import type * as sns from 'aws-cdk-lib/aws-sns';
import { Construct } from 'constructs';
import { ConstructValidationError } from '../core/errors';
import { assertPositive, assertRegion } from '../core/validation';

/**
 * Properties of the `BillingAlarm` construct.
 */
export interface BillingAlarmProps {
  /**
   * The estimated charges in USD above which the alarm enters the ALARM state. Must be greater than 0.
   *
   * @default none (required)
   */
  readonly thresholdUsd: number;

  /**
   * The SNS topic notified when the alarm enters the ALARM state. The topic policy must allow the alarm to publish.
   *
   * @default none (required)
   */
  readonly topic: sns.ITopic;

  /**
   * The physical name of the alarm. Leave it unset to let CDK generate a unique name.
   *
   * @default a name generated by CDK
   */
  readonly alarmName?: string;

  /**
   * The 12-digit account ID whose estimated charges the alarm watches. Adds the `LinkedAccount` dimension.
   * Use it only when the payer account publishes per-account billing metrics.
   *
   * @default none (the alarm watches the total estimated charges of the payer account)
   */
  readonly linkedAccountId?: string;
}

/**
 * A CloudWatch alarm on the `AWS/Billing` `EstimatedCharges` metric that notifies an SNS topic.
 *
 * The alarm is a backup to AWS Budgets: it reacts to current estimated charges, but it does not replace a budget.
 *
 * Billing alerts must be enabled first in the Billing preferences of the account, and that setting cannot be disabled.
 * The metric only exists in `us-east-1`, so the construct refuses to synthesize in any other region. When the stack region
 * is unresolved (environment-agnostic stack), it adds the warning `cdk-constructless:unresolved-region` instead.
 *
 * The metric is in USD only. Data takes about 15 minutes to appear after billing alerts are enabled.
 *
 * The `LinkedAccount` dimension exists only when the payer account publishes per-account metrics. Check it with
 * `aws cloudwatch list-metrics --namespace AWS/Billing --region us-east-1` before setting `linkedAccountId`.
 */
export class BillingAlarm extends Construct {
  /**
   * The wrapped `AWS::CloudWatch::Alarm` resource.
   */
  public readonly alarm: cloudwatch.Alarm;

  /**
   * @param scope the parent construct
   * @param id the construct id
   * @param props the alarm properties
   * @throws {ConstructValidationError} when the stack region is resolved and not `us-east-1`, when `thresholdUsd` is not greater than 0,
   * or when `linkedAccountId` is resolved and is not a 12-digit account ID
   */
  constructor(scope: Construct, id: string, props: BillingAlarmProps) {
    super(scope, id);

    const { thresholdUsd, topic, alarmName, linkedAccountId } = props;

    assertRegion(this, 'us-east-1', 'BillingAlarm');
    assertPositive(this, 'thresholdUsd', thresholdUsd);
    if (linkedAccountId !== undefined && !Token.isUnresolved(linkedAccountId) && !/^\d{12}$/.test(linkedAccountId)) {
      throw new ConstructValidationError(
        this,
        `linkedAccountId must be a 12-digit account ID, got "${linkedAccountId}"`,
      );
    }

    const metric = new cloudwatch.Metric({
      namespace: 'AWS/Billing',
      metricName: 'EstimatedCharges',
      dimensionsMap: {
        Currency: 'USD',
        ...(linkedAccountId ? { LinkedAccount: linkedAccountId } : {}),
      },
      statistic: 'Maximum',
      period: Duration.hours(6),
    });

    this.alarm = new cloudwatch.Alarm(this, 'Alarm', {
      metric,
      threshold: thresholdUsd,
      evaluationPeriods: 1,
      comparisonOperator: cloudwatch.ComparisonOperator.GREATER_THAN_THRESHOLD,
      treatMissingData: cloudwatch.TreatMissingData.NOT_BREACHING,
      alarmName,
    });
    this.alarm.addAlarmAction(new cw_actions.SnsAction(topic));
  }
}
