import { Stack } from 'aws-cdk-lib';
import * as iam from 'aws-cdk-lib/aws-iam';
import { Construct } from 'constructs';
import { suppressNag } from '../core/nag';

/**
 * The instance type a Budget Action stops through SSM automation.
 */
export enum StopInstancesTarget {
  /** Stop EC2 instances with the `AWS-StopEC2Instance` SSM automation document. */
  EC2 = 'EC2',
  /** Stop RDS instances with the `AWS-StopRdsInstance` SSM automation document. */
  RDS = 'RDS',
}

/**
 * Properties of the `BudgetActionExecutionRole` construct.
 */
export interface BudgetActionExecutionRoleProps {
  /**
   * The physical name of the IAM role. Leave it unset to let CDK generate a unique name.
   *
   * @default a name generated by CDK
   */
  readonly roleName?: string;
}

const STOP_DOCUMENT: Record<StopInstancesTarget, string> = {
  [StopInstancesTarget.EC2]: 'AWS-StopEC2Instance',
  [StopInstancesTarget.RDS]: 'AWS-StopRdsInstance',
};

const STOP_ACTIONS: Record<StopInstancesTarget, string[]> = {
  [StopInstancesTarget.EC2]: ['ec2:DescribeInstanceStatus', 'ec2:StopInstances'],
  [StopInstancesTarget.RDS]: ['rds:DescribeDBInstances', 'rds:StopDBInstance'],
};

/**
 * The cdk-nag `AwsSolutions-IAM5` finding ids that the wildcard resources of each target report.
 *
 * `AwsSolutions-IAM5` reports one finding per wildcard resource, so each finding id is acknowledged separately,
 * exactly as the validation report prints it.
 */
const STOP_NAG_FINDINGS: Record<StopInstancesTarget, string[]> = {
  [StopInstancesTarget.EC2]: [
    'AwsSolutions-IAM5[Resource::*]',
    'AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:ssm:*:*:document/AWS-StopEC2Instance]',
    'AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:ssm:*:*:automation-execution/*]',
    'AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:ssm:*:*:automation-definition/AWS-StopEC2Instance:*]',
  ],
  [StopInstancesTarget.RDS]: [
    'AwsSolutions-IAM5[Resource::*]',
    'AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:ssm:*:*:document/AWS-StopRdsInstance]',
    'AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:ssm:*:*:automation-execution/*]',
    'AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:ssm:*:*:automation-definition/AWS-StopRdsInstance:*]',
  ],
};

/**
 * The IAM execution role that AWS Budgets assumes to run a Budget Action.
 *
 * The trust policy allows only `budgets.amazonaws.com` acting for this account's budgets (`aws:SourceAccount` and `aws:SourceArn`).
 * `allowStopInstances` grants exactly the permissions that AWS's managed policy
 * `AWSBudgetsActions_RolePolicyForResourceAdministrationWithSSM` grants for stopping one instance type, restricted to calls
 * made through SSM (`aws:CalledVia` `ssm.amazonaws.com`). Start actions are never granted.
 *
 * Suppressions: the stop statements use wildcard resources (`*` for the EC2 or RDS actions, and `automation-execution/*` and
 * `automation-definition/<DOC>:*` for SSM), so cdk-nag reports four `AwsSolutions-IAM5` findings per stop target on the
 * role's default policy: `AwsSolutions-IAM5[Resource::*]`, `AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:ssm:*:*:document/<DOC>]`,
 * `AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:ssm:*:*:automation-execution/*]` and
 * `AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:ssm:*:*:automation-definition/<DOC>:*]`.
 * They are acknowledged with `suppressNag` and the reason "Budget Actions stop instances through SSM automation documents;
 * AWS documents these wildcard resources". The stop actions cannot be scoped to instance ARNs through SSM automation
 * without per-instance policies.
 *
 * Each `allowStopInstances` call adds its statements once per target; calling it again for the same target does nothing.
 */
export class BudgetActionExecutionRole extends Construct {
  /**
   * The wrapped `AWS::IAM::Role` that AWS Budgets assumes.
   */
  public readonly role: iam.Role;

  private readonly grantedTargets = new Set<StopInstancesTarget>();

  /**
   * @param scope the parent construct
   * @param id the construct id
   * @param props the role properties
   */
  constructor(scope: Construct, id: string, props: BudgetActionExecutionRoleProps = {}) {
    super(scope, id);

    const stack = Stack.of(this);

    this.role = new iam.Role(this, 'Role', {
      roleName: props.roleName,
      assumedBy: new iam.ServicePrincipal('budgets.amazonaws.com').withConditions({
        StringEquals: { 'aws:SourceAccount': stack.account },
        ArnLike: { 'aws:SourceArn': `arn:${stack.partition}:budgets::${stack.account}:budget/*` },
      }),
    });
  }

  /**
   * Grants the role the permissions to stop instances of one type through the SSM automation document for that type.
   *
   * The call also acknowledges the `AwsSolutions-IAM5` wildcard findings that this target's SSM statements report on the
   * role's default policy, so each target's findings are acknowledged when its statements are added.
   *
   * @param target the instance type to stop, `StopInstancesTarget.EC2` or `StopInstancesTarget.RDS`
   */
  public allowStopInstances(target: StopInstancesTarget): void {
    if (this.grantedTargets.has(target)) {
      return;
    }
    this.grantedTargets.add(target);

    const stack = Stack.of(this);
    const document = STOP_DOCUMENT[target];

    this.role.addToPolicy(
      new iam.PolicyStatement({
        actions: STOP_ACTIONS[target],
        resources: ['*'],
        conditions: {
          'ForAnyValue:StringEquals': { 'aws:CalledVia': ['ssm.amazonaws.com'] },
        },
      }),
    );

    this.role.addToPolicy(
      new iam.PolicyStatement({
        actions: ['ssm:StartAutomationExecution'],
        resources: [
          `arn:${stack.partition}:ssm:*:*:document/${document}`,
          `arn:${stack.partition}:ssm:*:*:automation-execution/*`,
          `arn:${stack.partition}:ssm:*:*:automation-definition/${document}:*`,
        ],
      }),
    );

    suppressNag(
      this.role.node.findChild('DefaultPolicy'),
      STOP_NAG_FINDINGS[target].map((id) => ({
        id,
        reason:
          'Budget Actions stop instances through SSM automation documents; AWS documents these wildcard resources',
      })),
    );
  }
}
