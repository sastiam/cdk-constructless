import { Names, RemovalPolicy, Token } from 'aws-cdk-lib';
import * as budgets from 'aws-cdk-lib/aws-budgets';
import * as organizations from 'aws-cdk-lib/aws-organizations';
import { Construct } from 'constructs';
import { ConstructValidationError } from '../core/errors';
import { assertIamActions, assertItemCount } from '../core/validation';
import {
  BudgetActionApprovalModel,
  type BudgetActionSubscriber,
  BudgetActionThresholdType,
  toActionSubscribers,
  validateActionThreshold,
} from './budget-action-common';
import { BudgetActionExecutionRole } from './budget-action-execution-role';
import { DEFAULT_DENIED_COMPUTE_ACTIONS } from './budget-deny-action';
import { BudgetNotificationType, type CostBudget } from './cost-budget';

/**
 * The longest SCP document that AWS Organizations accepts, in characters.
 */
const MAX_SCP_DOCUMENT_LENGTH = 5120;

/**
 * Matches an account ID (12 digits), an organizational unit ID (`ou-` prefix) or a root ID (`r-` prefix).
 */
const TARGET_ID_PATTERN = /^(\d{12}|ou-[0-9a-z]{4,32}-[a-z0-9]{8,32}|r-[0-9a-z]{4,32})$/;

/**
 * Properties of the `BudgetScpAction` construct.
 */
export interface BudgetScpActionProps {
  /**
   * The budget whose threshold runs the action. The action depends on this budget and uses its name.
   *
   * @default none (required)
   */
  readonly budget: CostBudget;

  /**
   * The account IDs, organizational unit IDs or root IDs that the SCP is attached to when the action runs. Between 1 and 100 items.
   * Account IDs are 12 digits, OU IDs start with `ou-` and root IDs start with `r-`.
   *
   * @default none (required)
   */
  readonly targetIds: string[];

  /**
   * The threshold that runs the action. A percentage from 0.01 to 1000 when `thresholdType` is `PERCENTAGE`;
   * an amount greater than 0 when `thresholdType` is `ABSOLUTE_VALUE`.
   *
   * @default 80
   */
  readonly threshold?: number;

  /**
   * How `threshold` is measured.
   *
   * @default BudgetActionThresholdType.PERCENTAGE
   */
  readonly thresholdType?: BudgetActionThresholdType;

  /**
   * Whether the threshold is compared against actual or forecasted spend.
   *
   * @default BudgetNotificationType.ACTUAL
   */
  readonly notificationType?: BudgetNotificationType;

  /**
   * Whether the action runs automatically or waits for approval. The default runs an unattended lab account without a person in the loop.
   *
   * @default BudgetActionApprovalModel.AUTOMATIC
   */
  readonly approvalModel?: BudgetActionApprovalModel;

  /**
   * The IAM actions that the SCP denies on all resources. Each entry must look like `service:Action`, for example
   * `sagemaker:CreateEndpoint`. The list replaces the defaults, so include the defaults you still need. The SCP document must not
   * exceed 5120 characters.
   *
   * @default DEFAULT_DENIED_COMPUTE_ACTIONS (ec2:RunInstances, ec2:StartInstances, lambda:CreateFunction, ecs:CreateService,
   * ecs:RunTask, rds:CreateDBInstance, rds:StartDBInstance)
   */
  readonly deniedActions?: string[];

  /**
   * The physical name of the service control policy. Leave it unset to let CDK generate a unique name of at most 128 characters.
   *
   * @default a name generated by CDK (Names.uniqueResourceName, at most 128 characters)
   */
  readonly policyName?: string;

  /**
   * The recipients of the action notifications. Between 1 and 11 items.
   *
   * @default none (required)
   */
  readonly subscribers: BudgetActionSubscriber[];

  /**
   * The role that AWS Budgets assumes to attach the SCP. When it is set, the construct grants it the attach, detach and describe
   * permissions for SCPs.
   *
   * @default a new BudgetActionExecutionRole created as the child `ExecutionRole` of this construct
   */
  readonly executionRole?: BudgetActionExecutionRole;
}

/**
 * A Budget Action that attaches a deny service control policy (SCP) to the given accounts, organizational units or root when a
 * `CostBudget` threshold is crossed.
 *
 * The construct wraps `AWS::Organizations::Policy` (`policy`, type `SERVICE_CONTROL_POLICY`, one Deny statement over `deniedActions` on `*`,
 * not attached to any target) and `AWS::Budgets::BudgetsAction` with `ActionType` `APPLY_SCP_POLICY` (`action`). The action attaches the
 * policy to `targetIds`, and it depends on the budget, so CloudFormation creates the budget first. The execution role is either
 * `executionRole` or a new `BudgetActionExecutionRole`, and it may attach, detach and describe SCPs.
 *
 * The policy is retained on stack deletion (`RemovalPolicy.RETAIN`), so an SCP that is attached during an incident is never deleted with the stack.
 *
 * Limits (the action does not cover these cases):
 * - Management account only: AWS Budgets applies SCPs only when the stack that contains this construct is deployed in the management account of the organization.
 * - SCPs do not affect the management account or service-linked roles, so the denied actions do not stop them.
 * - The SCP does not stop resources that already run, so pair it with `BudgetStopInstancesAction` to stop existing instances.
 * - Budgets data lags 8 to 12 hours, so the action can run long after the spend occurred.
 * - A reverted action is not re-evaluated in the same budget period unless it is reset manually.
 *
 * Suppressions: the execution role acknowledges its own `AwsSolutions-IAM5` wildcard finding for the SCP permissions (see
 * `BudgetActionExecutionRole.allowApplyScpPolicy`). This construct adds no suppressions of its own; the deny statement grants no access.
 *
 * @throws {ConstructValidationError} `targetIds must contain between 1 and 100 items, got <count>` when `targetIds` is empty or longer than 100,
 * `targetIds entries must be account, OU or root IDs, got "<value>"` for the first target that is not an account, OU or root ID,
 * `deniedActions entries must look like service:Action, got "<value>"` for the first denied action that is malformed,
 * `SCP document is <n> characters; the limit is 5120` when the SCP document is too long, and the errors of `validateActionThreshold`
 * and `toActionSubscribers` for an invalid `threshold` or `subscribers`
 */
export class BudgetScpAction extends Construct {
  /**
   * The wrapped `AWS::Organizations::Policy` of type `SERVICE_CONTROL_POLICY`. It is attached only through the Budget Action.
   */
  public readonly policy: organizations.CfnPolicy;

  /**
   * The wrapped `AWS::Budgets::BudgetsAction` resource.
   */
  public readonly action: budgets.CfnBudgetsAction;

  /**
   * The role that AWS Budgets assumes to attach the SCP, either `BudgetScpActionProps.executionRole` or the created `ExecutionRole`.
   */
  public readonly executionRole: BudgetActionExecutionRole;

  /**
   * @param scope the parent construct
   * @param id the construct id
   * @param props the action properties
   */
  constructor(scope: Construct, id: string, props: BudgetScpActionProps) {
    super(scope, id);

    const { budget, targetIds, subscribers } = props;
    const threshold = props.threshold ?? 80;
    const thresholdType = props.thresholdType ?? BudgetActionThresholdType.PERCENTAGE;
    const notificationType = props.notificationType ?? BudgetNotificationType.ACTUAL;
    const approvalModel = props.approvalModel ?? BudgetActionApprovalModel.AUTOMATIC;
    const deniedActions = props.deniedActions ?? [...DEFAULT_DENIED_COMPUTE_ACTIONS];

    assertItemCount(this, 'targetIds', targetIds, 1, 100);
    for (const targetId of targetIds) {
      if (!Token.isUnresolved(targetId) && !TARGET_ID_PATTERN.test(targetId)) {
        throw new ConstructValidationError(
          this,
          `targetIds entries must be account, OU or root IDs, got "${targetId}"`,
        );
      }
    }
    assertIamActions(this, 'deniedActions', deniedActions);
    validateActionThreshold(this, threshold, thresholdType);
    const subscriberProperties = toActionSubscribers(this, subscribers);

    const content = {
      Version: '2012-10-17',
      Statement: [{ Sid: 'BudgetDenyCompute', Effect: 'Deny', Action: deniedActions, Resource: '*' }],
    };
    // The length is only exact when no denied action is a token; unresolved values are checked at deploy time.
    if (!deniedActions.some((action) => Token.isUnresolved(action))) {
      const documentLength = JSON.stringify(content).length;
      if (documentLength > MAX_SCP_DOCUMENT_LENGTH) {
        throw new ConstructValidationError(
          this,
          `SCP document is ${documentLength} characters; the limit is ${MAX_SCP_DOCUMENT_LENGTH}`,
        );
      }
    }

    this.policy = new organizations.CfnPolicy(this, 'Policy', {
      type: 'SERVICE_CONTROL_POLICY',
      name: props.policyName ?? Names.uniqueResourceName(this, { maxLength: 128 }),
      content,
    });
    this.policy.applyRemovalPolicy(RemovalPolicy.RETAIN);

    this.executionRole = props.executionRole ?? new BudgetActionExecutionRole(this, 'ExecutionRole');
    this.executionRole.allowApplyScpPolicy();

    this.action = new budgets.CfnBudgetsAction(this, 'Action', {
      budgetName: budget.budgetName,
      actionType: 'APPLY_SCP_POLICY',
      actionThreshold: { type: thresholdType, value: threshold },
      definition: {
        scpActionDefinition: {
          policyId: this.policy.attrId,
          targetIds,
        },
      },
      executionRoleArn: this.executionRole.role.roleArn,
      notificationType,
      approvalModel,
      subscribers: subscriberProperties,
    });
    this.action.addDependency(budget.budget);
  }
}
