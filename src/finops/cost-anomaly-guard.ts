import { Names, Token } from 'aws-cdk-lib';
import * as ce from 'aws-cdk-lib/aws-ce';
import type * as sns from 'aws-cdk-lib/aws-sns';
import { Construct } from 'constructs';
import { ConstructValidationError } from '../core/errors';
import { assertEmails, assertItemCount, assertPositive } from '../core/validation';

/**
 * How often a Cost Anomaly Detection subscription sends its notifications.
 */
export enum AnomalyFrequency {
  /** Send one notification per day that contains anomalies. Valid for e-mail subscribers only. */
  DAILY = 'DAILY',
  /** Send one notification per week that contains anomalies. Valid for e-mail subscribers only. */
  WEEKLY = 'WEEKLY',
  /** Send a notification as soon as an anomaly is detected. Valid for an SNS topic only. */
  IMMEDIATE = 'IMMEDIATE',
}

/**
 * The monitor that Cost Anomaly Detection watches. Use one of the three shapes.
 *
 * - `services`: a `DIMENSIONAL` monitor on the `SERVICE` dimension, one anomaly stream per AWS service.
 * - `linkedAccounts`: a `CUSTOM` monitor on the `LINKED_ACCOUNT` dimension, for the listed member accounts.
 * - `existing`: no monitor is created; the subscription uses the monitor with the given ARN.
 */
export type AnomalyMonitorSource =
  | { readonly kind: 'services' }
  | { readonly kind: 'linkedAccounts'; readonly accountIds: string[] }
  | { readonly kind: 'existing'; readonly monitorArn: string };

/**
 * Properties of the `CostAnomalyGuard` construct.
 */
export interface CostAnomalyGuardProps {
  /**
   * The monitor that Cost Anomaly Detection watches. `linkedAccounts` takes between 1 and 10 account IDs, each a 12-digit
   * account ID. `existing` takes the ARN of a monitor that already exists, for example one that AWS created on its own.
   *
   * @default { kind: 'services' }
   */
  readonly monitor?: AnomalyMonitorSource;

  /**
   * The physical name of the anomaly monitor. Leave it unset to let CDK generate a unique name (at most 100 characters).
   * Ignored when `monitor.kind` is `existing`.
   *
   * @default a name generated by CDK (Names.uniqueResourceName, at most 100 characters)
   */
  readonly monitorName?: string;

  /**
   * The physical name of the anomaly subscription. Leave it unset to let CDK generate a unique name (at most 100 characters).
   *
   * @default a name generated by CDK (Names.uniqueResourceName, at most 100 characters)
   */
  readonly subscriptionName?: string;

  /**
   * The e-mail addresses that receive the anomaly notifications. Between 1 and 10 items; each must be a valid e-mail address.
   * Give either `emails` (non-empty) or `topic`, never both. E-mail subscribers require `DAILY` or `WEEKLY` frequency.
   *
   * @default none (provide emails or topic)
   */
  readonly emails?: string[];

  /**
   * The SNS topic that receives the anomaly notifications. Give either `emails` (non-empty) or `topic`, never both.
   * SNS subscribers require `IMMEDIATE` frequency. The topic policy must allow `costalerts.amazonaws.com` to publish: create it
   * with `AlertsTopic` and `allowCostAnomalyDetection: true`.
   *
   * @default none (provide emails or topic)
   */
  readonly topic?: sns.ITopic;

  /**
   * How often the subscription sends notifications. `DAILY` and `WEEKLY` are valid for `emails`; `IMMEDIATE` is valid for `topic`.
   *
   * @default DAILY for e-mail, IMMEDIATE for a topic
   */
  readonly frequency?: AnomalyFrequency;

  /**
   * The absolute total impact in USD at or above which an anomaly is reported. Must be greater than 0.
   *
   * @default 1
   */
  readonly thresholdUsd?: number;
}

/**
 * A Cost Anomaly Detection monitor and subscription that alert when spend deviates from the expected pattern by at least a USD
 * threshold. Use it alongside budgets: a service can spike ten times while the total stays under budget, and a budget does not
 * see that.
 *
 * The monitor is created as a `DIMENSIONAL` `SERVICE` monitor by default, or as a `CUSTOM` `LINKED_ACCOUNT` monitor when
 * `monitor.kind` is `linkedAccounts`. The subscription alerts when the `ANOMALY_TOTAL_IMPACT_ABSOLUTE` of an anomaly is greater
 * than or equal to `thresholdUsd`. The construct writes the threshold with `ThresholdExpression`, never with the deprecated
 * `Threshold`.
 *
 * Notifications go to e-mail (`emails`, `DAILY` or `WEEKLY`) or to one SNS topic (`topic`, `IMMEDIATE`). The SNS topic must allow
 * `costalerts.amazonaws.com` to publish: create it with `AlertsTopic` and `allowCostAnomalyDetection: true`.
 *
 * AWS may already have created a services monitor in the account. Creating a second one duplicates the stream of anomalies, so
 * reuse the existing monitor with `monitor: { kind: 'existing', monitorArn }` when that monitor is present.
 *
 * The construct creates no IAM role and no fixed-cost resource, so it adds no cdk-nag finding.
 */
export class CostAnomalyGuard extends Construct {
  /**
   * The ARN of the monitor that the subscription watches: the created monitor, or the `existing` ARN.
   */
  public readonly monitorArn: string;

  /**
   * The wrapped `AWS::CE::AnomalyMonitor` resource, or `undefined` when `monitor.kind` is `existing`.
   */
  public readonly monitor?: ce.CfnAnomalyMonitor;

  /**
   * The wrapped `AWS::CE::AnomalySubscription` resource.
   */
  public readonly subscription: ce.CfnAnomalySubscription;

  /**
   * @param scope the parent construct
   * @param id the construct id
   * @param props the monitor, subscription and threshold properties
   * @throws {ConstructValidationError} when neither or both of `emails` and `topic` are given, when `emails` does not contain 1 to 10
   * valid e-mail addresses, when e-mail subscribers use `IMMEDIATE` frequency, when an SNS topic uses a frequency other than
   * `IMMEDIATE`, when `thresholdUsd` is not greater than 0, or when `monitor.accountIds` does not contain 1 to 10 12-digit account IDs
   */
  constructor(scope: Construct, id: string, props: CostAnomalyGuardProps = {}) {
    super(scope, id);

    const emails = props.emails ?? [];
    const topic = props.topic;
    const hasEmails = emails.length > 0;
    const hasTopic = topic !== undefined;
    const thresholdUsd = props.thresholdUsd ?? 1;
    const source: AnomalyMonitorSource = props.monitor ?? { kind: 'services' };

    if (hasEmails === hasTopic) {
      throw new ConstructValidationError(this, 'provide emails or a topic, not both');
    }
    if (hasEmails) {
      assertItemCount(this, 'emails', emails, 1, 10);
      assertEmails(this, 'emails', emails);
    }

    const frequency = props.frequency ?? (hasTopic ? AnomalyFrequency.IMMEDIATE : AnomalyFrequency.DAILY);
    if (hasEmails && frequency === AnomalyFrequency.IMMEDIATE) {
      throw new ConstructValidationError(this, 'email subscribers require DAILY or WEEKLY frequency');
    }
    if (hasTopic && frequency !== AnomalyFrequency.IMMEDIATE) {
      throw new ConstructValidationError(this, 'SNS subscribers require IMMEDIATE frequency');
    }

    assertPositive(this, 'thresholdUsd', thresholdUsd);

    if (source.kind === 'linkedAccounts') {
      assertItemCount(this, 'monitor.accountIds', source.accountIds, 1, 10);
      for (const accountId of source.accountIds) {
        if (!Token.isUnresolved(accountId) && !/^\d{12}$/.test(accountId)) {
          throw new ConstructValidationError(
            this,
            `monitor.accountIds must be 12-digit account IDs, got "${accountId}"`,
          );
        }
      }
    }

    if (source.kind === 'existing') {
      this.monitorArn = source.monitorArn;
    } else {
      const monitorName = props.monitorName ?? Names.uniqueResourceName(this, { maxLength: 100 });
      this.monitor = new ce.CfnAnomalyMonitor(
        this,
        'Monitor',
        source.kind === 'services'
          ? { monitorName, monitorType: 'DIMENSIONAL', monitorDimension: 'SERVICE' }
          : {
              monitorName,
              monitorType: 'CUSTOM',
              monitorSpecification: JSON.stringify({
                Dimensions: { Key: 'LINKED_ACCOUNT', Values: source.accountIds },
              }),
            },
      );
      this.monitorArn = this.monitor.attrMonitorArn;
    }

    const subscribers = topic
      ? [{ type: 'SNS', address: topic.topicArn }]
      : emails.map((address) => ({ type: 'EMAIL', address }));

    this.subscription = new ce.CfnAnomalySubscription(this, 'Subscription', {
      subscriptionName: props.subscriptionName ?? Names.uniqueResourceName(this, { maxLength: 100 }),
      monitorArnList: [this.monitorArn],
      frequency,
      subscribers,
      thresholdExpression: JSON.stringify({
        Dimensions: {
          Key: 'ANOMALY_TOTAL_IMPACT_ABSOLUTE',
          MatchOptions: ['GREATER_THAN_OR_EQUAL'],
          Values: [String(thresholdUsd)],
        },
      }),
    });
  }
}
