import { Annotations, Names, Token } from 'aws-cdk-lib';
import * as budgets from 'aws-cdk-lib/aws-budgets';
import type * as sns from 'aws-cdk-lib/aws-sns';
import { Construct } from 'constructs';
import { ConstructValidationError } from '../core/errors';
import { assertItemCount, assertPositive, assertRange } from '../core/validation';

/**
 * The kind of spend a budget threshold is compared against.
 */
export enum BudgetNotificationType {
  /** Notify when the actual spend crosses the threshold. */
  ACTUAL = 'ACTUAL',
  /** Notify when the forecasted spend for the month crosses the threshold. */
  FORECASTED = 'FORECASTED',
}

/**
 * A percentage of the budget limit at which subscribers are notified.
 */
export interface BudgetThreshold {
  /**
   * The percentage of `limitUsd` that triggers the notification, from 0.01 to 1000.
   *
   * @default none (required)
   */
  readonly percent: number;

  /**
   * Whether the threshold is compared against actual or forecasted spend.
   *
   * @default BudgetNotificationType.ACTUAL
   */
  readonly type?: BudgetNotificationType;
}

/**
 * Properties of the `CostBudget` construct.
 */
export interface CostBudgetProps {
  /**
   * The monthly budget limit in USD. Must be greater than 0.
   *
   * @default none (required)
   */
  readonly limitUsd: number;

  /**
   * The physical name of the budget. Leave it unset to let CDK generate a unique name.
   *
   * @default a name generated by CDK (Names.uniqueResourceName, at most 100 characters)
   */
  readonly budgetName?: string;

  /**
   * The thresholds that trigger a notification. Between 1 and 5 items; each `percent` must be between 0.01 and 1000.
   * Notifications are created only when `emails` or `topic` is given.
   *
   * @default [ACTUAL 60, ACTUAL 80, ACTUAL 100, FORECASTED 100] (see DEFAULT_BUDGET_THRESHOLDS)
   */
  readonly thresholds?: BudgetThreshold[];

  /**
   * The e-mail addresses that receive every notification. Between 0 and 10 items.
   *
   * @default [] (no e-mail subscribers)
   */
  readonly emails?: string[];

  /**
   * The SNS topic that receives every notification. The topic policy must allow AWS Budgets to publish.
   *
   * @default none (no SNS subscriber)
   */
  readonly topic?: sns.ITopic;

  /**
   * The 12-digit account IDs whose costs this budget covers. Between 1 and 100 items.
   * Use it from the management account to budget one member account.
   *
   * @default none (the budget covers all linked accounts)
   */
  readonly linkedAccountIds?: string[];
}

/**
 * The thresholds used when `CostBudgetProps.thresholds` is not given: ACTUAL 60, ACTUAL 80, ACTUAL 100 and FORECASTED 100 percent.
 */
export const DEFAULT_BUDGET_THRESHOLDS: readonly BudgetThreshold[] = [
  { percent: 60, type: BudgetNotificationType.ACTUAL },
  { percent: 80, type: BudgetNotificationType.ACTUAL },
  { percent: 100, type: BudgetNotificationType.ACTUAL },
  { percent: 100, type: BudgetNotificationType.FORECASTED },
];

const ACCOUNT_ID_PATTERN = /^\d{12}$/;

/**
 * A monthly USD cost budget that notifies e-mail and SNS subscribers when spend crosses its thresholds.
 *
 * Budgets refreshes up to three times a day (8 to 12 h apart), so this is not a hard cap; use Budget Actions to act on spend.
 *
 * Budget Actions are not created by this construct. Use `budget` to attach them.
 */
export class CostBudget extends Construct {
  /**
   * The wrapped `AWS::Budgets::Budget` resource.
   */
  public readonly budget: budgets.CfnBudget;

  /**
   * The name of the budget, either `CostBudgetProps.budgetName` or the CDK-generated name.
   */
  public readonly budgetName: string;

  /**
   * @param scope the parent construct
   * @param id the construct id
   * @param props the budget properties
   * @throws {ConstructValidationError} when `limitUsd` is not greater than 0, when `thresholds` does not contain 1 to 5 items,
   * when a threshold `percent` is outside 0.01 to 1000, when `emails` does not contain 0 to 10 items,
   * when `linkedAccountIds` does not contain 1 to 100 items, or when a `linkedAccountIds` entry is not a 12-digit account ID
   */
  constructor(scope: Construct, id: string, props: CostBudgetProps) {
    super(scope, id);

    const limitUsd = props.limitUsd;
    const thresholds = props.thresholds ?? DEFAULT_BUDGET_THRESHOLDS;
    const emails = props.emails ?? [];
    const topic = props.topic;
    const linkedAccountIds = props.linkedAccountIds;

    assertPositive(this, 'limitUsd', limitUsd);

    if (props.thresholds !== undefined) {
      assertItemCount(this, 'thresholds', props.thresholds, 1, 5);
      props.thresholds.forEach((threshold, index) => {
        assertRange(this, `thresholds[${index}].percent`, threshold.percent, 0.01, 1000);
      });
    }

    assertItemCount(this, 'emails', emails, 0, 10);

    if (linkedAccountIds !== undefined) {
      assertItemCount(this, 'linkedAccountIds', linkedAccountIds, 1, 100);
      for (const accountId of linkedAccountIds) {
        if (!Token.isUnresolved(accountId) && !ACCOUNT_ID_PATTERN.test(accountId)) {
          throw new ConstructValidationError(this, `linkedAccountIds must be 12-digit account IDs, got "${accountId}"`);
        }
      }
    }

    this.budgetName = props.budgetName ?? Names.uniqueResourceName(this, { maxLength: 100 });

    const subscribers = [
      ...emails.map((address) => ({ subscriptionType: 'EMAIL', address })),
      ...(topic ? [{ subscriptionType: 'SNS', address: topic.topicArn }] : []),
    ];

    if (subscribers.length === 0) {
      Annotations.of(this).addWarningV2(
        'cdk-constructless:budget-without-subscribers',
        'CostBudget has no emails or topic; no notification will be sent',
      );
    }

    this.budget = new budgets.CfnBudget(this, 'Budget', {
      budget: {
        budgetName: this.budgetName,
        budgetType: 'COST',
        timeUnit: 'MONTHLY',
        budgetLimit: { amount: limitUsd, unit: 'USD' },
        ...(linkedAccountIds !== undefined ? { costFilters: { LinkedAccount: linkedAccountIds } } : {}),
      },
      ...(subscribers.length > 0
        ? {
            notificationsWithSubscribers: thresholds.map((threshold) => ({
              notification: {
                comparisonOperator: 'GREATER_THAN',
                thresholdType: 'PERCENTAGE',
                threshold: threshold.percent,
                notificationType: threshold.type ?? BudgetNotificationType.ACTUAL,
              },
              subscribers,
            })),
          }
        : {}),
    });
  }
}
