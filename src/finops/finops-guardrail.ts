import type * as iam from 'aws-cdk-lib/aws-iam';
import { Construct } from 'constructs';
import { AlertsTopic } from './alerts-topic';
import { BillingAlarm } from './billing-alarm';
import { BudgetActionExecutionRole, type StopInstancesTarget } from './budget-action-execution-role';
import { BudgetDenyAction } from './budget-deny-action';
import { BudgetStopInstancesAction } from './budget-stop-instances-action';
import { type BudgetThreshold, CostBudget } from './cost-budget';

/**
 * Properties of the `FinOpsGuardrail` construct.
 */
export interface FinOpsGuardrailProps {
  /**
   * The monthly budget limit in USD. Must be greater than 0.
   *
   * @default none (required)
   */
  readonly limitUsd: number;

  /**
   * The e-mail addresses that receive the alerts topic notifications and the Budget Action notifications. Between 0 and 10 items;
   * each must be a valid e-mail address and must confirm its subscription before it receives notifications. A Budget Action needs
   * between 1 and 11 subscribers, so set at least one address when `stopInstances` or `denyCompute` is given.
   *
   * @default none (required)
   */
  readonly emails: string[];

  /**
   * The thresholds at which the budget notifies the alerts topic. Between 1 and 5 items.
   *
   * @default the CostBudget defaults: ACTUAL 60, ACTUAL 80, ACTUAL 100 and FORECASTED 100 percent
   */
  readonly thresholds?: BudgetThreshold[];

  /**
   * The physical name of the budget. Leave it unset to let CDK generate a unique name.
   *
   * @default a name generated by CDK
   */
  readonly budgetName?: string;

  /**
   * The estimated charges in USD above which the billing alarm enters the ALARM state. When set, the construct creates a `BillingAlarm`
   * in `us-east-1` that notifies the alerts topic. Must be greater than 0 when set.
   *
   * @default none (no billing alarm is created)
   */
  readonly billingAlarmThresholdUsd?: number;

  /**
   * When set, the construct creates a `BudgetStopInstancesAction` that stops the listed instances when the threshold is crossed.
   * The action notifies the `emails` subscribers, never the alerts topic.
   *
   * @default none (no stop action is created)
   */
  readonly stopInstances?: {
    /**
     * The instance type that the action stops: `StopInstancesTarget.EC2` or `StopInstancesTarget.RDS`.
     *
     * @default none (required)
     */
    readonly target: StopInstancesTarget;

    /**
     * The instance IDs to stop. Between 1 and 100 items.
     *
     * @default none (required)
     */
    readonly instanceIds: string[];

    /**
     * The percentage of `limitUsd` that runs the action, from 0.01 to 1000.
     *
     * @default none (required)
     */
    readonly threshold: number;
  };

  /**
   * When set, the construct creates a `BudgetDenyAction` that attaches a deny policy to the given principals when the threshold is crossed.
   * The action notifies the `emails` subscribers, never the alerts topic.
   *
   * @default none (no deny action is created)
   */
  readonly denyCompute?: {
    /**
     * The roles that the deny policy is attached to.
     *
     * @default [] (no roles)
     */
    readonly roles?: iam.IRole[];

    /**
     * The users that the deny policy is attached to.
     *
     * @default [] (no users)
     */
    readonly users?: iam.IUser[];

    /**
     * The groups that the deny policy is attached to.
     *
     * @default [] (no groups)
     */
    readonly groups?: iam.IGroup[];

    /**
     * The percentage of `limitUsd` that runs the action, from 0.01 to 1000.
     *
     * @default none (required)
     */
    readonly threshold: number;

    /**
     * The IAM actions that the deny policy denies. Each entry must look like `service:Action`.
     *
     * @default DEFAULT_DENIED_COMPUTE_ACTIONS (ec2:RunInstances, ec2:StartInstances, lambda:CreateFunction, ecs:CreateService,
     * ecs:RunTask, rds:CreateDBInstance, rds:StartDBInstance)
     */
    readonly deniedActions?: string[];
  };
}

/**
 * A one-call cost guardrail for an account: an alerts topic, a monthly cost budget that notifies it, an optional billing alarm
 * that notifies it, and optional Budget Actions that stop instances or deny compute.
 *
 * The alerts topic is for notifications only and is never wired to an action: budget notifications and the billing alarm use it,
 * while each Budget Action notifies its own e-mail subscribers from `emails`. Wiring one topic to everything is a known failure
 * from the FinOps research, because an automation subscriber on the alerts topic runs on the first-cent alert.
 *
 * When both `stopInstances` and `denyCompute` are set, one `BudgetActionExecutionRole` (`ActionsRole`) is shared by both actions.
 * Otherwise each action creates its own execution role.
 *
 * Construct ids: `Alerts`, `Budget`, `BillingAlarm`, `StopInstances`, `DenyCompute` and `ActionsRole`. Changing them replaces the resources.
 */
export class FinOpsGuardrail extends Construct {
  /**
   * The wrapped `AlertsTopic`. Budget notifications and the billing alarm publish to its topic.
   */
  public readonly alerts: AlertsTopic;

  /**
   * The wrapped `CostBudget`.
   */
  public readonly budget: CostBudget;

  /**
   * The wrapped `BillingAlarm`, or `undefined` when `billingAlarmThresholdUsd` is not set.
   */
  public readonly billingAlarm?: BillingAlarm;

  /**
   * The wrapped `BudgetStopInstancesAction`, or `undefined` when `stopInstances` is not set.
   */
  public readonly stopAction?: BudgetStopInstancesAction;

  /**
   * The wrapped `BudgetDenyAction`, or `undefined` when `denyCompute` is not set.
   */
  public readonly denyAction?: BudgetDenyAction;

  /**
   * @param scope the parent construct
   * @param id the construct id
   * @param props the guardrail properties
   * @throws {ConstructValidationError} the errors of the wrapped constructs, for example when `limitUsd` is not greater than 0,
   * when `emails` does not contain 0 to 10 valid e-mail addresses, when a Budget Action has no subscriber because `emails` is empty,
   * or when `billingAlarmThresholdUsd` is set in a region other than `us-east-1`
   */
  constructor(scope: Construct, id: string, props: FinOpsGuardrailProps) {
    super(scope, id);

    const { emails, stopInstances, denyCompute } = props;
    const subscribers = emails.map((email) => ({ email }));

    this.alerts = new AlertsTopic(this, 'Alerts', { emails });

    this.budget = new CostBudget(this, 'Budget', {
      limitUsd: props.limitUsd,
      thresholds: props.thresholds,
      budgetName: props.budgetName,
      topic: this.alerts.topic,
    });

    if (props.billingAlarmThresholdUsd !== undefined) {
      this.billingAlarm = new BillingAlarm(this, 'BillingAlarm', {
        thresholdUsd: props.billingAlarmThresholdUsd,
        topic: this.alerts.topic,
      });
    }

    const sharedRole =
      stopInstances !== undefined && denyCompute !== undefined
        ? new BudgetActionExecutionRole(this, 'ActionsRole')
        : undefined;

    if (stopInstances !== undefined) {
      this.stopAction = new BudgetStopInstancesAction(this, 'StopInstances', {
        budget: this.budget,
        target: stopInstances.target,
        instanceIds: stopInstances.instanceIds,
        threshold: stopInstances.threshold,
        subscribers,
        executionRole: sharedRole,
      });
    }

    if (denyCompute !== undefined) {
      this.denyAction = new BudgetDenyAction(this, 'DenyCompute', {
        budget: this.budget,
        threshold: denyCompute.threshold,
        roles: denyCompute.roles,
        users: denyCompute.users,
        groups: denyCompute.groups,
        deniedActions: denyCompute.deniedActions,
        subscribers,
        executionRole: sharedRole,
      });
    }
  }
}
